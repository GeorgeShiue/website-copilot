# Phase 5: Edge Cases
# ──────────────────────────────────────────────────────────────────────


class TestEdgeCases:
    """Verify graceful handling of boundary conditions."""

    def test_nonexistent_page_type(self, rag: Rag) -> None:
        """A filter value that matches nothing should return 0 results."""
        rag.build_retriever(top_k=20, filter_dict={"page_type": "nonexistent"})
        rag.build_query_engine()
        response = rag.query("anything")
        assert len(response.source_nodes) == 0, (
            f"Expected 0 results for nonexistent filter, "
            f"got {len(response.source_nodes)}"
        )

    def test_empty_filter_dict(self, rag: Rag) -> None:
        """None filter should degrade gracefully to unfiltered retrieval."""
        rag.build_retriever(top_k=5, filter_dict=None)
        rag.build_query_engine()
        response = rag.query("張嘉惠 教授 機器學習 深度學習")
        assert len(response.source_nodes) > 0, (
            "None filter should return results (degrade to no filter)"
        )
        assert len(response.source_nodes) <= 5, (
            f"top_k=5 should limit results, got {len(response.source_nodes)}"
        )


