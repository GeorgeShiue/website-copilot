# Phase 4: Recall Completeness
# ──────────────────────────────────────────────────────────────────────


class TestRecallCompleteness:
    """Verify that with correct filter + query, the system retrieves what it should."""

    def test_paper_recall(self, rag: Rag) -> None:
        """Paper filter must include the main publication pages."""
        rag.build_retriever(top_k=30, filter_dict={"page_type": "paper"})
        rag.build_query_engine(cutoff=0.0)  # disable cutoff to avoid filtering nodes
        response = rag.query("論文 發表 journal conference thesis PhD 碩博士論文")
        returned_titles = {
            n.node.metadata.get("page_title", "") for n in response.source_nodes
        }
        expected = {"Publication", "Publication by Year", "Thesis Advised"}
        missing = expected - returned_titles
        assert not missing, (
            f"Paper recall failure — missing pages: {missing}. "
            f"Returned: {returned_titles}"
        )

    def test_personnel_recall(self, rag: Rag) -> None:
        """Personnel filter must return nodes from personnel pages."""
        rag.build_retriever(top_k=20, filter_dict={"page_type": "personnel"})
        rag.build_query_engine()
        response = rag.query("成員 學生 教授 指導教授")
        returned_titles = {
            n.node.metadata.get("page_title", "") for n in response.source_nodes
        }
        # Advisor is currently classified as general, not personnel.
        # Verify at least one known personnel page is retrieved.
        personnel_pages = {
            "Members",
            "Activities",
            "Join WIDM",
            "Letter to potential students",
        }
        hit = returned_titles & personnel_pages
        assert hit, (
            f"Personnel recall failure — no known personnel page found. "
            f"Returned: {returned_titles}"
        )


