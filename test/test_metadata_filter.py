class TestFilterIsolation:
    """Verify that pre-filter correctly restricts results by metadata."""

    @pytest.mark.parametrize(
        "page_type", ["personnel", "announcement", "paper", "general"]
    )
    def test_single_filter_page_type(self, rag: Rag, page_type: str) -> None:
        """All retrieved nodes must match the requested page_type."""
        rag.build_retriever(top_k=20, filter_dict={"page_type": page_type})
        rag.build_query_engine()
        response = rag.query(page_type)  # use the page type as a simple query
        _assert_all_nodes_match_filter(response.source_nodes, "page_type", page_type)
        logger.info(
            f"page_type={page_type}: {len(response.source_nodes)} nodes returned, "
            f"all with correct page_type"
        )

    def test_single_filter_year(self, rag: Rag) -> None:
        """All retrieved nodes must match the requested year."""
        test_year = 2024
        rag.build_retriever(top_k=20, filter_dict={"year": test_year})
        rag.build_query_engine()
        response = rag.query("publication paper")
        _assert_all_nodes_match_filter(response.source_nodes, "year", test_year)

    def test_multi_filter_combination(self, rag: Rag) -> None:
        """Combined page_type + year filter must satisfy both constraints."""
        rag.build_retriever(
            top_k=20,
            filter_dict={"page_type": "paper", "year": 2025},
        )
        rag.build_query_engine()
        response = rag.query("transformer attention")
        for node in response.source_nodes:
            assert node.node.metadata.get("page_type") == "paper"
            assert node.node.metadata.get("year") == 2025


