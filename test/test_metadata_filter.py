class TestFilterPenetration:
    """Verify that pre-filter isolates by metadata, NOT by content similarity.

    The key insight: these tests assert metadata correctness, NOT empty results.
    Announcement pages may contain paper-related keywords (e.g., award notices
    congratulating a paper acceptance). Non-empty results with correct metadata
    are valid — empty results would be a bonus but not required.
    """

    def test_announcement_isolation(self, rag: Rag) -> None:
        """Paper-related query under announcement filter must not leak paper nodes."""
        rag.build_retriever(top_k=20, filter_dict={"page_type": "announcement"})
        rag.build_query_engine()
        response = rag.query("transformer attention BERT deep learning")
        _assert_all_nodes_match_filter(
            response.source_nodes, "page_type", "announcement"
        )

    def test_paper_isolation_reverse(self, rag: Rag) -> None:
        """Award-related query under paper filter must not leak announcement nodes."""
        rag.build_retriever(top_k=20, filter_dict={"page_type": "paper"})
        rag.build_query_engine()
        response = rag.query("校內奬項 賀 獲獎 第一名")
        _assert_all_nodes_match_filter(response.source_nodes, "page_type", "paper")


