class TestRegression:
    """Regression tests for known failures.

    Q5 (from rag_cutoff04_topk10_eval.md) failed because award/announcement
    pages were mixed into paper query results. Metadata filter should fix this.
    """

    def test_q5_paper_query_no_leakage(self, rag: Rag) -> None:
        """Q5 fix: paper-filtered query must not retrieve non-paper nodes."""
        rag.build_retriever(top_k=20, filter_dict={"page_type": "paper"})
        rag.build_query_engine(cutoff=0.0)
        response = rag.query("實驗室近三年發表過哪些論文？", log_sources=True)

        # Assertion 1: No leakage — all nodes must be paper type
        _assert_all_nodes_match_filter(response.source_nodes, "page_type", "paper")

        # Assertion 2: Recall — publication pages must be present
        returned_titles = {
            n.node.metadata.get("page_title", "") for n in response.source_nodes
        }
        assert any("Publication" in t for t in returned_titles), (
            f"No publication pages retrieved — recall failure. "
            f"Returned: {returned_titles}"
        )

    def test_q5_paper_query_relevancy(self, rag: Rag) -> None:
        """Q5 fix: paper-filtered query should pass relevancy evaluation."""
        rag.build_retriever(top_k=20, filter_dict={"page_type": "paper"})
        rag.build_query_engine(cutoff=0.0)
        response = rag.query("實驗室近三年發表過哪些論文？")

        faithfulness_result, relevancy_result = rag.evaluate(
            "實驗室近三年發表過哪些論文？", response
        )
        assert relevancy_result.passing, (
            f"Q5 regression: Relevancy still failing after metadata filter. "
            f"Details: {relevancy_result.feedback}"
        )
