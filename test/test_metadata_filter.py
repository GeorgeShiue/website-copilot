"""Metadata filter validation tests.

Tests are organized into 6 phases:
  Phase 1: Metadata injection integrity (ingestion layer)
  Phase 2: Pre-filter isolation correctness (retrieval layer)
  Phase 3: Semantic penetration tests
  Phase 4: Recall completeness
  Phase 5: Edge cases
  Phase 6: Q5 regression test (original motivation for metadata filtering)

Pipeline rebuild strategy:
  - If Qdrant VectorStore exists and is consistent with results.json → skip rebuild
  - Otherwise → clean + rebuild automatically
"""

import logging
from pathlib import Path
from typing import Any, Sequence

import pytest
from llama_index.core.schema import BaseNode, NodeWithScore

from app.configs.rag_config import WEBPAGES_DATA_FOLDER_PATH
from app.modules.rag import Rag

logger = logging.getLogger(__name__)

# ──────────────────────────────────────────────────────────────────────
# Constants
# ──────────────────────────────────────────────────────────────────────
RESULTS_JSON_PATH = Path(WEBPAGES_DATA_FOLDER_PATH) / "results.json"
QDRANT_DB_PATH = (
    Path(WEBPAGES_DATA_FOLDER_PATH) / ".." / "rag" / "results" / "qdrant_db"
)

# Map of page_title → expected page_type (sampled from results.json)
# Generated by crawling results — update when crawler URL→page_type mapping changes.
EXPECTED_PAGE_TYPES: dict[str, str] = {
    "Web Intelligence and Data Mining Lab": "general",
    "Advisor": "general",  # /advisor not mapped to personnel in current crawler
    "校內奬項": "announcement",
    "Publication": "paper",
    "Publication by Year": "paper",
    "Thesis Advised": "paper",
    "Members": "personnel",
    "Activities": "personnel",
    "Join WIDM": "personnel",
    "Letter to potential students": "personnel",
}

# Pages expected to have date metadata under specific strategies
PAGES_WITH_HEADING_YEAR = {"Publication by Year"}
PAGES_WITH_POST_DATE = {"UWIDE2"}
PAGES_WITH_TRAILING_DATE = {"校內奬項"}
PAGES_WITH_FALLBACK_YEAR = {"Publication by Year"}
PAGES_WITHOUT_DATE = {"Web Intelligence and Data Mining Lab"}


# ──────────────────────────────────────────────────────────────────────
# Helpers
# ──────────────────────────────────────────────────────────────────────


def _has_existing_qdrant_db() -> bool:
    """Check if Qdrant storage directory exists and is non-empty."""
    return QDRANT_DB_PATH.exists() and any(QDRANT_DB_PATH.iterdir())


def _set_logging() -> None:
    """Enable debug logging for test diagnostics."""
    logging.basicConfig(level=logging.DEBUG)


def _get_nodes_by_page_title(
    nodes: Sequence[BaseNode] | None, title: str
) -> list[BaseNode]:
    """Filter nodes by page_title metadata."""
    if nodes is None:
        return []
    return [n for n in nodes if n.metadata.get("page_title") == title]


def _assert_all_nodes_match_filter(
    source_nodes: list[NodeWithScore],
    key: str,
    expected_value: Any,
) -> None:
    """Assert all returned nodes have the expected metadata value.

    This is the CORE assertion pattern for all filter isolation tests.
    """
    for node in source_nodes:
        actual = node.node.metadata.get(key)
        assert actual == expected_value, (
            f"Filter leak detected: node from "
            f"'{node.node.metadata.get('page_title', '?')}' "
            f"has {key}={actual!r}, expected {expected_value!r}"
        )


# ──────────────────────────────────────────────────────────────────────
# Fixtures
# ──────────────────────────────────────────────────────────────────────


@pytest.fixture(scope="module")
def rag() -> Rag:
    """Provide a Rag instance with fully rebuilt nodes, vector store, and index.

    Always rebuilds from scratch to guarantee metadata injection integrity.
    The existing Qdrant DB (if any) was built before metadata fields existed,
    so loading it would lose ``page_type``/``year``/``description`` metadata.
    """
    _set_logging()
    instance = Rag()

    if _has_existing_qdrant_db():
        logger.info(
            "Cleaning stale Qdrant DB (pre-dates metadata injection) — rebuilding"
        )
        instance.clean_vector_store()

    instance.build_nodes()
    instance.build_vector_store()
    instance.build_index()

    return instance


# ──────────────────────────────────────────────────────────────────────
# Phase 1: Metadata Injection Integrity (Ingestion Layer)
# ──────────────────────────────────────────────────────────────────────


class TestMetadataInjection:
    """Verify that build_nodes() correctly injects metadata from results.json."""

    def test_page_type_propagation(self, rag: Rag) -> None:
        """Every node must carry a valid page_type matching its source page."""
        for page_title, expected_ptype in EXPECTED_PAGE_TYPES.items():
            matching = _get_nodes_by_page_title(rag.nodes, page_title)
            assert matching, f"No nodes found for page '{page_title}'"
            for node in matching:
                actual = node.metadata.get("page_type")
                assert actual == expected_ptype, (
                    f"Node from '{page_title}' has page_type={actual!r}, "
                    f"expected {expected_ptype!r}"
                )

    def test_date_extraction_heading_year(self, rag: Rag) -> None:
        """Strategy 1: Section heading (### 2026) should set year."""
        for page_title in PAGES_WITH_HEADING_YEAR:
            nodes = _get_nodes_by_page_title(rag.nodes, page_title)
            nodes_with_year = [n for n in nodes if n.metadata.get("year") is not None]
            assert nodes_with_year, (
                f"No nodes from '{page_title}' have year metadata "
                f"— heading year strategy may have failed"
            )
            for n in nodes_with_year:
                assert isinstance(n.metadata["year"], int), (
                    f"year metadata should be int, got {type(n.metadata['year'])}"
                )
                assert isinstance(n.metadata["year"], int), (
                    f"year metadata should be int, got {type(n.metadata['year'])}"
                )

    def test_date_extraction_post_date(self, rag: Rag) -> None:
        """Strategy 2: Post date line should set year/month/day."""
        for page_title in PAGES_WITH_POST_DATE:
            nodes = _get_nodes_by_page_title(rag.nodes, page_title)
            dated = [n for n in nodes if n.metadata.get("year") is not None]
            assert dated, f"No nodes from '{page_title}' have date metadata"
            sample = dated[0]
            assert isinstance(sample.metadata.get("year"), int)
            assert isinstance(sample.metadata.get("month"), int)
            assert isinstance(sample.metadata.get("day"), int)
            logger.info(
                f"Post date test: '{page_title}' → year={sample.metadata['year']}, "
                f"month={sample.metadata['month']}, day={sample.metadata['day']}"
            )

    def test_date_extraction_trailing_date(self, rag: Rag) -> None:
        """Strategy 3: Trailing date (— Mon. DD, YYYY) should set year/month/day."""
        for page_title in PAGES_WITH_TRAILING_DATE:
            nodes = _get_nodes_by_page_title(rag.nodes, page_title)
            dated = [n for n in nodes if n.metadata.get("year") is not None]
            assert dated, f"No nodes from '{page_title}' have date metadata"
            sample = dated[0]
            assert isinstance(sample.metadata.get("year"), int)
            assert isinstance(sample.metadata.get("month"), int)
            assert isinstance(sample.metadata.get("day"), int)

    def test_date_extraction_no_date_pages(self, rag: Rag) -> None:
        """Pages without date clues should NOT have year metadata."""
        for page_title in PAGES_WITHOUT_DATE:
            nodes = _get_nodes_by_page_title(rag.nodes, page_title)
            dated = [n for n in nodes if n.metadata.get("year") is not None]
            if dated:
                # This may happen if fallback strategy (4) is too aggressive.
                # Log a warning rather than failing — inspect manually.
                logger.warning(
                    f"Page '{page_title}' unexpectedly has year metadata"
                    f" on {len(dated)}/{len(nodes)} nodes"
                )

    def test_description_integrity(self, rag: Rag) -> None:
        """All nodes should have a non-empty description (from results.json)."""
        if rag.nodes is None:
            pytest.skip("No nodes loaded — cannot test description integrity")
        empty_desc = [
            n for n in rag.nodes if not (n.metadata.get("description") or "").strip()
        ]
        if empty_desc:
            titles = set(n.metadata.get("page_title", "?") for n in empty_desc)
            logger.warning(
                f"{len(empty_desc)} nodes from {titles} have empty description"
            )


